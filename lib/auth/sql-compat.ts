/** Rewrite the small SQLite dialect this app sends so Postgres can run it. */

export function splitStatements(sql: string): string[] {
  const parts: string[] = [];
  let start = 0;
  let index = 0;
  while (index < sql.length) {
    const char = sql[index];
    if (char === "'" || char === '"') {
      index = skipQuoted(sql, index, char);
      continue;
    }
    if (char === "-" && sql[index + 1] === "-") {
      while (index < sql.length && sql[index] !== "\n") index += 1;
      continue;
    }
    if (char === ";") {
      parts.push(sql.slice(start, index));
      start = index + 1;
    }
    index += 1;
  }
  parts.push(sql.slice(start));
  return parts.map((part) => part.trim()).filter(Boolean);
}

/** Returns null when the statement is SQLite-only and has no Postgres equivalent. */
export function translateStatement(sql: string): string | null {
  const trimmed = sql.trim();
  const tableInfo = /^pragma\s+table_info\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*$/i.exec(trimmed);
  if (tableInfo) {
    const table = tableInfo[1].toLowerCase();
    return `SELECT ordinal_position - 1 AS cid, column_name AS name, data_type AS type,
      CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
      column_default AS dflt_value, 0 AS pk
      FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = '${table}'
      ORDER BY ordinal_position`;
  }
  if (/^pragma\b/i.test(trimmed)) return null;

  let translated = replacePlaceholders(trimmed);
  translated = translated.replace(/\bBEGIN\s+(IMMEDIATE|EXCLUSIVE|DEFERRED)\b/gi, "BEGIN");
  translated = translated.replace(
    /\bsqlite_master\b/gi,
    `(SELECT c.relname AS name, CASE WHEN c.relkind = 'r' THEN 'table' WHEN c.relkind = 'i' THEN 'index' ELSE c.relkind::text END AS type
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public') sqlite_master`,
  );
  translated = translated.replace(
    /\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );
  if (/^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(translated)) {
    translated = translated.replace(/^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i, "INSERT INTO");
    if (!/\bON\s+CONFLICT\b/i.test(translated)) translated = `${translated} ON CONFLICT DO NOTHING`;
  }
  return translated;
}

function replacePlaceholders(sql: string): string {
  let out = "";
  let index = 0;
  let count = 0;
  while (index < sql.length) {
    const char = sql[index];
    if (char === "'" || char === '"') {
      const end = skipQuoted(sql, index, char);
      out += sql.slice(index, end);
      index = end;
      continue;
    }
    if (char === "-" && sql[index + 1] === "-") {
      const start = index;
      while (index < sql.length && sql[index] !== "\n") index += 1;
      out += sql.slice(start, index);
      continue;
    }
    if (char === "?") {
      count += 1;
      out += `$${count}`;
      index += 1;
      continue;
    }
    out += char;
    index += 1;
  }
  return out;
}

function skipQuoted(sql: string, index: number, quote: string): number {
  let cursor = index + 1;
  while (cursor < sql.length) {
    if (sql[cursor] === quote) {
      if (sql[cursor + 1] === quote) {
        cursor += 2;
        continue;
      }
      return cursor + 1;
    }
    cursor += 1;
  }
  return cursor;
}
