import assert from "node:assert/strict";
import { isUniqueConflict } from "../lib/billing/analysis";
import { splitStatements, translateStatement } from "../lib/auth/sql-compat";

const parts = splitStatements("PRAGMA journal_mode = WAL; SELECT 1; SELECT 'a;b' AS v;");
assert.deepEqual(parts, ["PRAGMA journal_mode = WAL", "SELECT 1", "SELECT 'a;b' AS v"]);

assert.equal(translateStatement("PRAGMA journal_mode = WAL"), null);
assert.equal(translateStatement("BEGIN IMMEDIATE"), "BEGIN IMMEDIATE");
assert.equal(translateStatement("BEGIN EXCLUSIVE"), "BEGIN EXCLUSIVE");
assert.equal(translateStatement("BEGIN DEFERRED"), "BEGIN");
assert.equal(translateStatement("BEGIN"), "BEGIN");

const placeholders = translateStatement("SELECT * FROM users WHERE email = ? AND name = ?");
assert.equal(placeholders, "SELECT * FROM users WHERE email = $1 AND name = $2");

const quoted = translateStatement("SELECT '?' AS q WHERE email = ?");
assert.equal(quoted, "SELECT '?' AS q WHERE email = $1");

const ignore = translateStatement(
  "INSERT OR IGNORE INTO favorite_sports (user_id, sport_id, created_at) VALUES (?, ?, ?)",
);
assert.equal(
  ignore,
  "INSERT INTO favorite_sports (user_id, sport_id, created_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING",
);

const catalog = translateStatement("SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'users'");
assert.match(catalog ?? "", /information_schema|pg_class/);
assert.match(catalog ?? "", /sqlite_master/);

const info = translateStatement("PRAGMA table_info(sponsorship_requests)");
assert.match(info ?? "", /information_schema\.columns/);
assert.match(info ?? "", /sponsorship_requests/);

const identity = translateStatement(
  "CREATE TABLE IF NOT EXISTS login_attempts (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL)",
);
assert.match(identity ?? "", /GENERATED BY DEFAULT AS IDENTITY/);
assert.doesNotMatch(identity ?? "", /AUTOINCREMENT/);

assert.equal(isUniqueConflict(Object.assign(new Error("duplicate key value violates unique constraint \"analysis_ledger_user_id_cache_key_key\""), { code: "23505" })), true);
assert.equal(isUniqueConflict(new Error("UNIQUE constraint failed: analysis_ledger.user_id, analysis_ledger.cache_key")), true);
assert.equal(isUniqueConflict(new Error("connection refused")), false);

console.log("sql compat ok");
