-- Account, session, billing, and sponsor tables mirrored from SQLite.
-- password_hash stays the stored scrypt$salt$hash text. This file has no credentials.
-- Idempotent. Does not drop tables and does not truncate provider data.

create table if not exists users (
  id text primary key,
  email text not null unique,
  name text not null,
  password_hash text not null,
  email_verified_at text,
  draft_json text,
  created_at text not null
);

create table if not exists sessions (
  token_hash text primary key,
  user_id text not null references users (id),
  expires_at text not null
);

create table if not exists tokens (
  token_hash text primary key,
  user_id text not null references users (id),
  purpose text not null,
  expires_at text not null,
  used_at text
);

create table if not exists login_attempts (
  id bigint generated by default as identity primary key,
  email text not null,
  created_at text not null
);

create table if not exists planned_moments (
  id text primary key,
  user_id text not null references users (id),
  sport_id text not null,
  place_id text not null,
  place_label text not null,
  period text not null,
  window_label text not null,
  planned_start text not null,
  planned_end text not null,
  note text not null default '',
  last_snapshot_at text,
  last_score_label text,
  created_at text not null,
  updated_at text not null
);

create table if not exists saved_searches (
  id text primary key,
  user_id text not null references users (id),
  sport_id text not null,
  place_id text not null,
  place_label text not null,
